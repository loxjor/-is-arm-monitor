import type { WallData } from './wall';
import type { WorkspaceData } from './workspace';

/**
 * Снимок всей сцены — используется и для undo внутри сессии (Т-05), и как
 * формат, который в Этапе 4 (Т-03) уйдёт на сервер целиком одним PUT.
 * version — на будущее: контракт, который поедет в базу, версионируем с
 * первого дня, а не когда придётся мигрировать первую сохранённую запись.
 *
 * WallData и WorkspaceData оба в сантиметрах (Т-06) — единая система единиц
 * на границе компонентов. Полей уровня плана (название, подложка) здесь
 * сознательно нет — они появятся в Этапе 4 вместе с сохранением.
 */
export interface SceneData {
  version: 1;
  walls: WallData[];
  workspaces: WorkspaceData[];
}
