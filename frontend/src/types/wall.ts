import type { Cm } from '../utils/scale';

/**
 * Узел графа стен — общая точка, которую делят все сходящиеся в ней стены.
 * Угол здания — это узел с двумя (или больше) рёбрами, а не отдельное
 * накопленное состояние: подвинуть узел значит подвинуть угол сразу для
 * всех сегментов, которые на него ссылаются.
 */
export interface WallNode {
  id: string;
  x: Cm;
  y: Cm;
}

/** Ребро графа — сегмент стены между двумя узлами. Толщина — своё поле, ни от чего не выводится. */
export interface WallSegment {
  id: string;
  startNodeId: string;
  endNodeId: string;
  thickness: Cm;
}

/**
 * Старая (version 1) плоская форма стены — отрезок с собственными x/y/length/
 * rotation, без общих вершин. Оставлена только для чтения ранее сохранённых
 * планов и миграции в графовую модель (см. utils/wallGraph.ts) — новый код
 * её больше не производит.
 */
export interface WallData {
  id: string;
  /** Точка начала стены (X), см */
  x: Cm;
  /** Точка начала стены (Y), см */
  y: Cm;
  /** Длина стены вдоль направления rotation, см */
  length: Cm;
  /** Толщина стены, одинаковая по всей длине, см */
  thickness: Cm;
  /** Угол направления стены в градусах */
  rotation: number;
}
